ALTER TABLE usuario DROP CONSTRAINT ck_usuario_perfil;
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'OPERADOR', 'COZINHA'));

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao VARCHAR(30) NOT NULL,
    usuario_responsavel_id BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    usuario_alvo_id BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    ocorrido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_auditoria_acao CHECK (acao IN ('CRIACAO_USUARIO', 'CONSULTA_USUARIO', 'LISTAGEM_USUARIOS'))
);

CREATE INDEX idx_auditoria_usuario_responsavel ON auditoria (usuario_responsavel_id);
CREATE INDEX idx_auditoria_usuario_alvo ON auditoria (usuario_alvo_id);

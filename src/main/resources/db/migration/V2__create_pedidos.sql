CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    canal VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    total NUMERIC(28, 2) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_pedido_canal CHECK (canal IN ('APP', 'TOTEM', 'BALCAO', 'PICKUP', 'WEB')),
    CONSTRAINT ck_pedido_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'PAGAMENTO_RECUSADO')),
    CONSTRAINT ck_pedido_total CHECK (total >= 0)
);

CREATE INDEX idx_pedido_unidade ON pedido (unidade_id);

CREATE TABLE item_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedido (id),
    produto_unidade_id BIGINT NOT NULL REFERENCES produto_unidade (id),
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    CONSTRAINT uk_item_pedido_produto_unidade UNIQUE (pedido_id, produto_unidade_id),
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_pedido_preco CHECK (preco_unitario >= 0)
);

CREATE INDEX idx_item_pedido_produto_unidade ON item_pedido (produto_unidade_id);

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedido (id),
    status VARCHAR(15) NOT NULL,
    valor NUMERIC(28, 2) NOT NULL,
    processado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_pagamento_status CHECK (status IN ('APROVADO', 'RECUSADO')),
    CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);

CREATE TABLE movimentacao_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estoque_id BIGINT NOT NULL REFERENCES estoque (id),
    pedido_id BIGINT REFERENCES pedido (id),
    tipo VARCHAR(15) NOT NULL,
    quantidade INTEGER NOT NULL,
    quantidade_fisica_apos INTEGER NOT NULL,
    quantidade_reservada_apos INTEGER NOT NULL,
    registrada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_movimentacao_tipo CHECK (tipo IN ('REPOSICAO', 'RESERVA', 'BAIXA', 'LIBERACAO')),
    CONSTRAINT ck_movimentacao_pedido CHECK ((tipo = 'REPOSICAO') = (pedido_id IS NULL)),
    CONSTRAINT ck_movimentacao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_movimentacao_saldo CHECK (
        quantidade_fisica_apos >= 0
        AND quantidade_reservada_apos >= 0
        AND quantidade_reservada_apos <= quantidade_fisica_apos
    )
);

CREATE INDEX idx_movimentacao_estoque ON movimentacao_estoque (estoque_id, id);
CREATE INDEX idx_movimentacao_pedido ON movimentacao_estoque (pedido_id);

CREATE TABLE evento_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedido (id),
    status_anterior VARCHAR(30),
    status_novo VARCHAR(30) NOT NULL,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_evento_pedido_transicao CHECK (
        (status_anterior IS NULL AND status_novo = 'AGUARDANDO_PAGAMENTO')
        OR (status_anterior IS NOT NULL AND status_anterior = 'AGUARDANDO_PAGAMENTO'
            AND status_novo IN ('PAGO', 'PAGAMENTO_RECUSADO'))
    )
);

CREATE INDEX idx_evento_pedido ON evento_pedido (pedido_id, id);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE unidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE produto_unidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produto (id),
    unidade_id BIGINT NOT NULL REFERENCES unidade (id),
    preco NUMERIC(12, 2) NOT NULL,
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (produto_id, unidade_id),
    CONSTRAINT ck_preco_positivo CHECK (preco >= 0)
);

CREATE TABLE estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_unidade_id BIGINT NOT NULL UNIQUE REFERENCES produto_unidade (id),
    quantidade_fisica INTEGER NOT NULL DEFAULT 0,
    quantidade_reservada INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_quantidade_valida CHECK (
        quantidade_fisica >= 0
        AND quantidade_reservada >= 0
        AND quantidade_reservada <= quantidade_fisica
    )
);
